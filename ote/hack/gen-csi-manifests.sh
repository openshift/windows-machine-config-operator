#!/bin/bash
# gen-csi-manifests.sh generates the Windows CSI node driver manifests into Go source.
#
# The example manifests live under hack/manifests/csi and stay the single source of truth. The
# OTE module cannot embed them: it is a separate module, go:embed patterns cannot contain "..",
# symlinks are rejected as irregular files, and the extension binary runs without a checkout.
# Generating them into ote/test/e2e/csi_manifests_gen.go keeps one maintained copy in hack/ and
# makes drift a lint failure instead of a silent difference.
#
# USAGE
#    gen-csi-manifests.sh [output file]   (default: ote/test/e2e/csi_manifests_gen.go)
set -o errexit
set -o nounset
set -o pipefail

WMCO_ROOT=$(dirname "${BASH_SOURCE}")/../..
cd "${WMCO_ROOT}"

OUT=${1:-ote/test/e2e/csi_manifests_gen.go}
SOURCE_DIR=hack/manifests/csi

{
  echo '// Code generated by ote/hack/gen-csi-manifests.sh from hack/manifests/csi; DO NOT EDIT.'
  echo
  echo 'package winc'
  echo
  echo '// csiDriverManifests maps a platform to its example Windows CSI node driver DaemonSet.'
  echo 'var csiDriverManifests = map[string]string{'
  for manifest in "${SOURCE_DIR}"/*/01-example-driver-daemonset.yaml; do
    platform=$(basename "$(dirname "${manifest}")")
    printf '\t"%s": `' "${platform}"
    cat "${manifest}"
    printf '`,\n'
  done
  echo '}'
} > "${OUT}"
gofmt -s -w "${OUT}"
